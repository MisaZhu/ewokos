#!/bin/sh
#
# Generate the host ABI export table for libdl.
#
#   usage: gen_export.sh NM OUTPUT ARCHIVE...
#
# Why this exists: EwokOS links every program statically, and GNU ld creates no
# dynamic section at all for an ET_EXEC link, so -Wl,-E/--export-dynamic is a
# no-op - the host binary carries no .dynsym for a plugin's undefined symbols to
# resolve against. This script builds that missing table by nm-ing the archives
# EWOK_LIBC names and emitting a C array of (name, address) pairs.
#
# The references are emitted STRONG, not weak. That is deliberate and is the
# whole mechanism: an undefined weak symbol does not make ld extract an archive
# member, so a weak table would export only whatever the host happened to use
# itself, and a plugin calling anything else would resolve to 0 at runtime. With
# strong references, linking the generated object into an app pulls in exactly
# the members a plugin might need. The cost is that a plugin host is bigger than
# the same program without libdl - which is why this covers EWOK_LIBC only, and
# why symbols from libm, libx and friends go through dl_host_publish() instead.
#
# Names are emitted sorted by strcmp() so dl_abi.c can binary search.

set -e

if [ $# -lt 3 ]; then
	echo "usage: gen_export.sh NM OUTPUT ARCHIVE..." >&2
	exit 2
fi

NM="$1"
OUT="$2"
shift 2

LC_ALL=C
export LC_ALL

dir=$(dirname "$OUT")
mkdir -p "$dir"
names="$dir/.gen_export.$$.names"
sorted="$dir/.gen_export.$$.sorted"
trap 'rm -f "$names" "$sorted"' 0 1 2 3 15

: > "$names"
for lib in "$@"; do
	if [ ! -f "$lib" ]; then
		echo "gen_export.sh: warning: $lib is absent, skipping" >&2
		continue
	fi
	# -g: external symbols only. --defined-only: drop the undefined refs,
	# which are precisely what this table exists to satisfy. The awk filter
	# keeps only real definitions - T/D/B/R text,data,bss,rodata plus W/V
	# weak - and rejects 'A' (absolute linker symbols, meaningless as a
	# runtime address) and 'U'/'w' (undefined).
	"$NM" -g --defined-only "$lib" 2>/dev/null \
		| awk 'NF == 3 && $2 ~ /^[TDBRWV]$/ { print $3 }' >> "$names" || true
done

# Only a well-formed C identifier can be referenced through the __asm__ label
# trick used below, so anything carrying '.', '$' or a leading digit is dropped
# rather than emitted as broken C. sort -u also collapses the same symbol
# defined by more than one archive, which would otherwise be a duplicate
# initializer and, worse, a non-deterministic lookup result.
sort -u "$names" | grep -E '^[A-Za-z_][A-Za-z0-9_]*$' > "$sorted" || true

count=$(wc -l < "$sorted" | tr -d ' ')
if [ "$count" -eq 0 ]; then
	echo "gen_export.sh: no exportable symbols found in: $*" >&2
	echo "gen_export.sh: were the archives built before libs/dl?" >&2
	exit 1
fi

{
	echo "/* GENERATED by libs/dl/gen_export.sh - do not edit."
	echo " *"
	echo " * Host ABI export table ($count symbols). Every global symbol defined"
	echo " * by the archives EWOK_LIBC names, so a plugin's undefined references"
	echo " * resolve the way they would against a shared libc on Linux."
	echo " *"
	echo " * INVARIANT: sorted by strcmp(name). dl_abi.c binary searches it, so"
	echo " * an out-of-order entry silently misses rather than fails loudly."
	echo " */"
	echo ""
	echo "#include <stdint.h>"
	echo "#include <dl/dl.h>"
	echo ""
	while read -r s; do
		# The __asm__ label gives the declaration the symbol's real assembler
		# name while keeping the C identifier unique and prefixed. Declaring
		# 'extern void printf(void)' instead would collide with GCC's builtin
		# and be rejected; an array declaration carries no type information,
		# which is all we need since only the address is used.
		echo "extern const char SYM_${s}[] __asm__(\"${s}\");"
	done < "$sorted"
	echo ""
	echo "const dl_symbol_t __ewok_dl_abi[] = {"
	while read -r s; do
		printf '\t{ "%s", (uintptr_t)(void *)SYM_%s },\n' "$s" "$s"
	done < "$sorted"
	echo "};"
	echo ""
	echo "const uint32_t __ewok_dl_abi_count ="
	echo "\t(uint32_t)(sizeof(__ewok_dl_abi) / sizeof(__ewok_dl_abi[0]));"
} > "$OUT"

echo "gen_export.sh: $count symbols -> $OUT"
